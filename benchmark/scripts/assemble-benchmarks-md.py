#!/usr/bin/env python3
"""Phase 09 (M6) task 12 / PRD section 16.3: assembles the repository
root's BENCHMARKS.md from every experiment's committed markdown
fragment plus the AC1-AC9 scorecard. Run after all eight experiments
and the AC scorecard script have produced their output in
benchmark/results/ - this script does no measurement itself, only
assembly, so it is safe to re-run standalone against existing results.
"""
import pathlib

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
RESULTS_DIR = REPO_ROOT / "benchmark" / "results"

EXPERIMENT_FRAGMENTS = [
    "experiment-1-threshold-sweep.md",
    "experiment-2-guard-ablation.md",
    "experiment-3-embedding-model-comparison.md",
    "experiment-4-hnsw-tuning.md",
    "experiment-5-concurrency-ceiling.md",
    "experiment-6-compact-object-headers.md",
    "experiment-7-failover-timing.md",
    "experiment-8-cost-simulation.md",
]

HEADLINE_TEMPLATE = """# Aether Gateway - Benchmarks

Generated by `make bench` (docs/plan/09-milestone-m6-benchmarking.md).
Every number below comes from a real, committed run - the raw CSVs
backing each table are in `benchmark/results/`, and the harness that
produced them is `gateway-bench` (Java) plus `benchmark/scripts/`
(k6/Python for the load-generation experiments).

**Headline**: at a 0.94 cosine threshold with the entity guard active,
semantic caching measured a 13.16% hit rate and 8.0% false-hit rate
against the 502-prompt hand-labelled corpus (below the PRD's 35%/5%
targets - see the AC scorecard and experiment 2 below for why),
cutting simulated spend 0.1% across that same corpus (dwarfed by the
long-context bucket's token volume - see experiment 8) and reducing
cache-hit end-to-end latency to a measured 8.9ms p95 (AC2, well under
the 50ms target). Failover from an injected provider outage completed
in a measured p99 of 67.92ms across 100 independent trials (AC6, well
under the 500ms target).

"""


def main():
    parts = [HEADLINE_TEMPLATE]

    for name in EXPERIMENT_FRAGMENTS:
        path = RESULTS_DIR / name
        if path.exists():
            # Fragments live in benchmark/results/ and link images/CSVs
            # relative to themselves; BENCHMARKS.md lives at the repo
            # root, so rewrite those relative links on the way in.
            text = path.read_text()
            text = text.replace("](experiment-", "](benchmark/results/experiment-")
            text = text.replace("`experiment-", "`benchmark/results/experiment-")
            parts.append(text)
            parts.append("\n---\n\n")
        else:
            parts.append(f"\n> **{name} missing** - re-run the corresponding experiment before publishing.\n\n---\n\n")

    scorecard_path = RESULTS_DIR / "ac-scorecard.md"
    if scorecard_path.exists():
        parts.append(scorecard_path.read_text())
    else:
        parts.append("\n> **AC scorecard missing** - run `python3 benchmark/scripts/write-ac-scorecard.py benchmark/results` first.\n")

    output_path = REPO_ROOT / "BENCHMARKS.md"
    output_path.write_text("".join(parts))
    print(f"Wrote {output_path}")


if __name__ == "__main__":
    main()
