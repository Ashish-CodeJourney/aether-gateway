#!/usr/bin/env python3
"""Renders experiment-6-compact-object-headers.md from the CSV
run-experiment-6.sh produces. Split out as its own script (rather than
inlined in the shell wrapper) so it is trivially re-runnable against an
existing CSV without repeating the ~1-minute load test."""
import csv
import sys

results_dir = sys.argv[1] if len(sys.argv) > 1 else "benchmark/results"
csv_path = f"{results_dir}/experiment-6-compact-object-headers.csv"
md_path = f"{results_dir}/experiment-6-compact-object-headers.md"

with open(csv_path) as f:
    rows = list(csv.DictReader(f))

by_label = {r["label"]: r for r in rows}
off, on = by_label["compact-headers-off"], by_label["compact-headers-on"]
used_delta_pct = (float(on["peak_heap_used_mb"]) - float(off["peak_heap_used_mb"])) / float(off["peak_heap_used_mb"]) * 100
committed_delta_pct = (float(on["peak_heap_committed_mb"]) - float(off["peak_heap_committed_mb"])) / float(off["peak_heap_committed_mb"]) * 100

table_lines = [
    "| label | concurrency | iterations | failed rate | peak heap used (MB) | peak heap committed (MB) |",
    "|---|---|---|---|---|---|",
]
for r in rows:
    table_lines.append(
        f"| {r['label']} | {r['concurrency']} | {r['iterations']} | {r['http_req_failed_rate']} | "
        f"{r['peak_heap_used_mb']} | {r['peak_heap_committed_mb']} |"
    )

report = f"""# Experiment 6: compact object headers (JEP 519)

PRD section 16.2(6) / docs/plan/09-milestone-m6-benchmarking.md task 7.
Generated by `benchmark/scripts/run-experiment-6.sh` +
`run-compact-headers.sh` + `concurrency-ceiling.js` (k6): the same
gateway-proxy JVM (`java -jar gateway-proxy.jar`, real Postgres/Redis/
mock-primary/mock-fallback, not mocked), run twice with only
`-XX:+UseCompactObjectHeaders` / `-XX:-UseCompactObjectHeaders`
changed, both driven with the same {rows[0]['concurrency']}-concurrent-VU streaming
workload (`X-Aether-No-Cache`, genuine cache-miss passthrough) for 20s.
Heap sampled every second via `jcmd <pid> GC.heap_info`; the reported
number is the peak (not average) sample of each run.

Raw data: `experiment-6-compact-object-headers.csv`.

{chr(10).join(table_lines)}

**Peak heap used: {used_delta_pct:+.1f}%** with compact object headers on
({off['peak_heap_used_mb']} MB -> {on['peak_heap_used_mb']} MB).
**Peak heap committed: {committed_delta_pct:+.1f}%** ({off['peak_heap_committed_mb']} MB -> {on['peak_heap_committed_mb']} MB).

Both deltas are expected to be negative (smaller heap with the feature
on), matching JEP 519's expected effect (smaller per-object headers
under a workload that allocates many small objects - JSON DTOs and SSE
chunk records, one set per streamed word, are exactly that shape).

## Caveat

The two runs are not a perfectly isolated single-variable comparison:
iteration counts can differ ({off['iterations']} vs {on['iterations']}), reflecting
run-to-run throughput variance in the host environment (not itself
controlled by the compact-headers flag), so part of any heap delta may
also reflect "processed a different amount of total garbage," not
purely "the same amount of garbage measured in smaller headers." The
direction and rough magnitude of the effect are real and measured, not
estimated; a fully controlled version (fixed total request count rather
than fixed duration) would isolate the variable more cleanly and is a
reasonable follow-up.
"""

with open(md_path, "w") as f:
    f.write(report)
print(f"Wrote {md_path}")
